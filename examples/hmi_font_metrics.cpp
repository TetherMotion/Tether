// hmi_font_metrics.cpp — dump glyb/HarfBuzz advance metrics for the HMI
// scene text ops as a TypeScript module consumed by TetherWebUI's
// scene→SVG renderer, so web text anchoring uses the exact same glyph
// engine (glyb: FreeType + HarfBuzz) as the native Vulkan renderer.
//
// Usage: hmi_font_metrics <output.ts> [font-path]
//   font-path defaults to DejaVu Sans Mono under /usr/share/fonts.

#include <algorithm>
#include <atomic>
#include <cstdint>
#include <cstring>
#include <fstream>
#include <iostream>
#include <map>
#include <memory>
#include <mutex>
#include <string>
