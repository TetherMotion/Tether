#include "glyph.h"

namespace {

// Same content-guessed direction/script shaping VolcanoPlot uses —
// upstream text_shaper_hb hardcodes LTR/Latin.
struct ShaperGuess : text_shaper {
    void shape(std::vector<glyph_shape>& shapes,
               text_segment& segment) override {
        auto* face = static_cast<font_face_ft*>(segment.face);
        face->get_metrics(segment.font_size);
        hb_font_t* hbfont = face->get_hbfont(segment.font_size);
        hb_language_t hblang = hb_language_from_string(
            segment.language.c_str(), (int)segment.language.size());
        hb_buffer_t* buf = hb_buffer_create();
        hb_buffer_set_language(buf, hblang);
        hb_buffer_add_utf8(buf, segment.text.c_str(),
                           (int)segment.text.size(), 0,
                           (int)segment.text.size());
        hb_buffer_guess_segment_properties(buf);
        hb_shape(hbfont, buf, nullptr, 0);
        unsigned n = 0;
        auto* info = hb_buffer_get_glyph_infos(buf, &n);
        auto* pos = hb_buffer_get_glyph_positions(buf, &n);
        for (unsigned i = 0; i < n; ++i)
            shapes.push_back({info[i].codepoint, info[i].cluster,
                              pos[i].x_offset, pos[i].y_offset,
                              pos[i].x_advance, pos[i].y_advance});
        hb_buffer_destroy(buf);
    }
};

float advanceEm(font_manager_ft& fm, ShaperGuess& shaper,
                font_face* face, const std::string& s, int px) {
    std::vector<glyph_shape> shapes;
    // glyb font_size is 26.6 fixed-point pixels
    text_segment seg(s, "en", face, px * 64, 0, 0, 0);
    shaper.shape(shapes, seg);
    float adv = 0.0f;
    for (const auto& g : shapes) adv += g.x_advance / 64.0f;
    return adv / float(px);
}

} // namespace

int main(int argc, char** argv) {
    if (argc < 2) {
        std::cerr << "usage: hmi_font_metrics <output.ts> [font-path]\n";
        return 2;
    }
    // DejaVu Sans Mono — the family the web SVG backend requests and
    // hmi_vulkan.cpp rasterizes with; advances are uniform per glyph.
    const char* fontPath = argc > 2 ? argv[2]
        : "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf";

    font_manager_ft fm;
    fm.scanFontPath(fontPath);
    auto* face = fm.findFontByPath(fontPath);
    if (!face) {
        std::cerr << "font not found: " << fontPath << "\n";
        return 1;
    }
    ShaperGuess shaper;

    std::string chars;
    for (int c = 32; c <= 126; ++c) chars += char(c);
    const std::string extra =
        "°µ±²³×÷·—–…■●▲▼←→↑↓≈≤≥≠∞ΩαβγΔΣπτφω";
    chars += extra;

    constexpr int kRefPx = 100;
    std::ofstream out(argv[1]);
    out << "/**\n"
        << " * Generated by Tether examples/hmi_font_metrics.cpp — DO NOT EDIT.\n"
        << " * glyb (FreeType+HarfBuzz) advance metrics in em units, shared by\n"
        << " * the web scene→SVG text layout and the native Vulkan renderer.\n"
        << " */\n"
        << "export const HMI_FONT_EM = 16;\n\n"
        << "/** advance of `s` at font size `size` (scene units) */\n"
        << "export function hmiTextWidth(s: string, size: number): number {\n"
        << "  const ADV: Record<string, number> = {";
    bool first = true;
    for (size_t i = 0; i < chars.size();) {
        auto uc = utf8_to_utf32_code(chars.data() + i);
        if (uc.len <= 0) break;
        std::string one(chars, i, size_t(uc.len));
        float adv = advanceEm(fm, shaper, face, one, kRefPx);
        if (!first) out << ", ";
        first = false;
        out << "'";
        for (unsigned char c : one) {
            if (c == '\'' || c == '\\') out << '\\';
            out << char(c);
        }
        out << "':" << adv;
        i += size_t(uc.len);
    }
    out << "};\n"
        << "  const FALLBACK_ADV = 0.5;\n"
        << "  let w = 0;\n"
        << "  for (const ch of s) w += (ADV[ch] ?? FALLBACK_ADV) * size;\n"
        << "  return w;\n"
        << "}\n";
    std::cout << "wrote " << argv[1] << " (" << chars.size() << " chars)\n";
    return 0;
}
