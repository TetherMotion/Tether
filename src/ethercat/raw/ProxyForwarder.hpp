/**
 * @file ProxyForwarder.hpp
 * @brief Linux AF_PACKET forwarder for the external-source PDO path
 *        ("EtherCAT proxy").
 *
 * Three bound packet sockets plus one pump thread:
 *
 *   - ecat_fd_  — bound to the EtherCAT bus interface; kernel BPF accepts
 *                 only EtherCAT frames whose FIRST datagram index lies in
 *                 the configured band (the slave responses to injected
 *                 PDO datagrams) → forwarded verbatim to the proxy iface.
 *   - proxy_fd_ — bound to the proxy interface; BPF accepts first-idx ∈
 *                 band → userspace re-validates the whole datagram chain
 *                 (PDO = logical commands only, every idx in-band) →
 *                 injected onto the bus interface unchanged.
 *   - mon_fd_   — bound to the proxy interface; BPF accepts EtherCAT
 *                 frames with first-idx OUTSIDE the band → ignored +
 *                 counted + rate-limited error log (the monitor the
 *                 feature contract requires).
 *
 * PACKET_IGNORE_OUTGOING on all sockets prevents TX echoes from looping
 * back.  The bus-interface filter mirrors the configured wire
 * encapsulation (untagged or VID-restricted) so proxy responses honour
 * the same VLAN rules as master's own traffic.
 *
 * @internal Internal header — not installed, not part of the public API.
 */

#pragma once

#include "tether/ethercat/ProxyForwardConfig.hpp"
#include "tether/ethercat/Types.hpp"                 // WireEncap, Command

#include <atomic>
#include <cstdint>
#include <cstddef>
#include <optional>
#include <string>
#include <thread>

namespace EtherCAT {

class ProxyForwarder {
public:
    ProxyForwarder() = default;
    ~ProxyForwarder() { stop(); }

    ProxyForwarder(const ProxyForwarder&)            = delete;
    ProxyForwarder& operator=(const ProxyForwarder&) = delete;

    /**
     * @brief Open the sockets and start the pump thread.
     * @param cfg          Validated proxy config (band + proxy ifname).
     * @param ecat_ifindex Kernel ifindex of the EtherCAT bus interface.
     * @param encap        Wire encapsulation — the ecat-side BPF keeps its
     *                     VID clause so forwarded responses honour the
     *                     same tag rules as the master's own traffic.
     * @param filter       Resolved address/value whitelist — explicit or
     *                     auto-generated by Master.  nullptr → PDO-only
     *                     validation.
     * @return false on any setup failure (lastError() set, no fd leaks).
     */
    bool start(const ProxyForwardConfig& cfg, int ecat_ifindex,
               const EtherCAT::WireEncap& encap,
               const ProxyPdoFilter* filter);
    void stop();
    bool running() const { return running_.load(std::memory_order_acquire); }

    ProxyForwardStats stats() const;
    const std::string& lastError() const { return last_error_; }

    /**
     * @brief Userspace validation for injected frames — the correctness
     *        fallback the BPF cannot express.
     *
     * Layout: [eth 14][+802.1Q 4][EtherCAT frame header 2][datagram]+.
     * Returns true iff the EtherCAT frame is well-formed AND every
     * datagram is a logical command (LRD/LWR/LRW — the PDO commands)
     * carrying an idx inside [idx_lo, idx_hi].  Any positional/broadcast
     * command or out-of-band index rejects the whole frame, so the
     * external source can never interfere with the master's own
     * transactions or FMMU/mailbox registers.
     */
    static bool frameIsInBandPdo(const uint8_t* frame, size_t len,
                                 uint8_t idx_lo, uint8_t idx_hi);

    /**
     * @brief One-stop ingress validation: structural PDO/band check plus,
     *        when `filter` is non-null, the address/value whitelist.
     *
     * Every datagram's logical span must be covered by access rules and
     * every overlapped value-constraint cell satisfied — see
     * ProxyPdoFilter::allows().
     */
    static bool framePassesFilter(const uint8_t* frame, size_t len,
                                  uint8_t idx_lo, uint8_t idx_hi,
                                  const ProxyPdoFilter* filter);

private:
    int  openFilteredSocket(int ifindex, const char* diag_name);
    void pumpLoop();
    void drainEcat();
    void drainProxy();
    void drainMonitor();
#if defined(__linux__)
    void drainUdp();
    bool openUdpListener(const ProxyForwardConfig& cfg,
                         const EtherCAT::WireEncap& encap);
    /// Re-encapsulate a validated bus-side frame for the last UDP peer.
    void sendUdpReply(const uint8_t* frame, size_t len);
#endif
    bool sendRaw(int fd, int ifindex, const uint8_t* frame, size_t len);
    /**Per-datagram ACL pass over an ALREADY structurally-valid frame. */
    static bool chainPassesFilter(const uint8_t* frame, size_t len,
                                  const ProxyPdoFilter& filter);

    std::atomic<bool> running_{false};
    std::atomic<bool> stop_flag_{false};
    std::thread pump_;

    int ecat_fd_  = -1;
    int proxy_fd_ = -1;
    int mon_fd_   = -1;
    int stop_fd_  = -1;
    int udp_fd_   = -1;            // optional ETG.1000.3 input
    int ecat_ifindex_  = 0;
    int proxy_ifindex_ = 0;
    uint8_t band_lo_ = 0;
    uint8_t band_hi_ = 0;
    /// Synthesised outer header for decapsulated UDP input: eth (+802.1Q).
    uint8_t udp_eth_hdr_[18] = {};
    uint8_t udp_eth_len_  = 0;     // 14 untagged, 18 tagged
    uint16_t udp_port_    = 0;
    /// Last-seen UDP peer for response re-encapsulation (single source).
    std::atomic<uint32_t> udp_peer_ip_{0};
    std::atomic<uint16_t> udp_peer_port_{0};
    std::string last_error_;
    /**Armed address/value whitelist — copied from the config at start(),
     * read-only for the pump thread thereafter. */
    std::optional<ProxyPdoFilter> filter_;

    std::atomic<uint64_t> rx_forwarded_{0};
    std::atomic<uint64_t> tx_forwarded_{0};
    std::atomic<uint64_t> tx_rejected_{0};
    std::atomic<uint64_t> filtered_{0};
    std::atomic<uint64_t> out_of_band_{0};
    std::atomic<uint64_t> send_errors_{0};
};

} // namespace EtherCAT
