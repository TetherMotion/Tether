GCodeProgram::GCodeProgram(const GCodeOptions& opts)
    : opts_(opts), nextLineNumber_(opts.lineNumberIncrement) {}

void GCodeProgram::addBlock(const GCodeBlock& block) {
    GCodeBlock b = block;
    if (opts_.useLineNumbers && b.lineNumber < 0) {
        b.lineNumber = nextLineNumber_;
        nextLineNumber_ += opts_.lineNumberIncrement;
    }
    blocks_.push_back(b);
}

void GCodeProgram::addBlock(const std::string& line) {
    GCodeBlock block;
    block.comment = line;
    addBlock(block);
}

void GCodeProgram::addComment(const std::string& comment) {
    GCodeBlock block;
    block.comment = comment;
    blocks_.push_back(block);
}

void GCodeProgram::addBlankLine() {
    GCodeBlock block;
    blocks_.push_back(block);
}

void GCodeProgram::addProgramStart() {
    addComment("Program generated by MotionReplanner");
    
    if (opts_.useMetric) {
        addUnitsMetric();
    } else {
        addUnitsInch();
    }
    
    if (opts_.absoluteMode) {
        addAbsoluteMode();
    } else {
        addIncrementalMode();
    }
}

void GCodeProgram::addProgramEnd() {
    GCodeBlock block;
    block.mCode = "M30";
    block.comment = "End program";
    addBlock(block);
}

void GCodeProgram::addUnitsMetric() {
    GCodeBlock block;
    block.gCode = "G21";
    block.comment = "Metric units";
    addBlock(block);
}

void GCodeProgram::addUnitsInch() {
    GCodeBlock block;
    block.gCode = "G20";
    block.comment = "Inch units";
    addBlock(block);
}

void GCodeProgram::addAbsoluteMode() {
    GCodeBlock block;
    block.gCode = "G90";
    block.comment = "Absolute positioning";
    addBlock(block);
}

void GCodeProgram::addIncrementalMode() {
    GCodeBlock block;
    block.gCode = "G91";
    block.comment = "Incremental positioning";
    addBlock(block);
}

void GCodeProgram::addRapid(double x, double y, double z) {
    GCodeBlock block;
    block.gCode = "G0";
    block.position[0] = x; block.hasPosition[0] = true;
    block.position[1] = y; block.hasPosition[1] = true;
    block.position[2] = z; block.hasPosition[2] = true;
    addBlock(block);
    
    currentX_ = x; currentY_ = y; currentZ_ = z;
}

