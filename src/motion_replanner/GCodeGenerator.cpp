std::string GCodeProgram::toString() const {
    std::ostringstream ss;
    write(ss);
    return ss.str();
}

bool GCodeProgram::saveToFile(const std::string& filename) const {
    std::ofstream file(filename);
    if (!file.is_open()) return false;
    write(file);
    return file.good();
}

void GCodeProgram::write(std::ostream& out) const {
    for (const auto& block : blocks_) {
        std::string line = block.toString(opts_);
        if (!line.empty() || block.comment.empty()) {
            out << line << "\n";
        }
    }
}

double GCodeProgram::estimateDuration() const {
    double duration = 0.0;
    double lastX = 0, lastY = 0, lastZ = 0;
    double currentFeed = opts_.defaultFeedRate;
    
    for (const auto& block : blocks_) {
        double x = lastX, y = lastY, z = lastZ;
        
        if (block.hasPosition[0]) x = block.position[0];
        if (block.hasPosition[1]) y = block.position[1];
        if (block.hasPosition[2]) z = block.position[2];
        
        double dist = std::sqrt(
            (x - lastX) * (x - lastX) +
            (y - lastY) * (y - lastY) +
            (z - lastZ) * (z - lastZ)
        );
        
        double feed = (block.feedRate > 0) ? block.feedRate : currentFeed;
        if (block.gCode == "G0") {
            feed = opts_.rapidRate;
        }
        
        if (dist > 0 && feed > 0) {
            duration += dist / (feed / 60.0);  // Convert mm/min to mm/s
        }
        
        if (block.feedRate > 0) currentFeed = block.feedRate;
        lastX = x; lastY = y; lastZ = z;
    }
    
    return duration;
}

std::pair<std::array<double, 3>, std::array<double, 3>> GCodeProgram::getBounds() const {
    std::array<double, 3> minBounds = {1e9, 1e9, 1e9};
    std::array<double, 3> maxBounds = {-1e9, -1e9, -1e9};
    
    for (const auto& block : blocks_) {
        for (int i = 0; i < 3; ++i) {
            if (block.hasPosition[i]) {
                minBounds[i] = std::min(minBounds[i], block.position[i]);
                maxBounds[i] = std::max(maxBounds[i], block.position[i]);
            }
        }
    }
    
    return {minBounds, maxBounds};
}

