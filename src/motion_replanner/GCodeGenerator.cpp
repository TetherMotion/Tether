void GCodeProgram::addDwell(double seconds) {
    GCodeBlock block;
    block.gCode = "G4";
    // P parameter in seconds or milliseconds depending on dialect
    std::ostringstream ss;
    ss << "G4 P" << std::fixed << std::setprecision(3) << seconds;
    block.comment = "";
    addBlock(ss.str());
}

