void GCodeProgram::addLinear(double x, double y, double z, double feedRate) {
    GCodeBlock block;
    block.gCode = "G1";
    block.position[0] = x; block.hasPosition[0] = true;
    block.position[1] = y; block.hasPosition[1] = true;
    block.position[2] = z; block.hasPosition[2] = true;
    
    if (feedRate > 0 && feedRate != currentFeed_) {
        block.feedRate = feedRate;
        currentFeed_ = feedRate;
    }
    
    addBlock(block);
    currentX_ = x; currentY_ = y; currentZ_ = z;
}

