void GCodeProgram::addDwell(double seconds) {
    GCodeBlock block;
    block.gCode = "G4";
    std::ostringstream ss;
    ss << "G4 P" << std::fixed << std::setprecision(3) << seconds;
    block.comment = "";
    addBlock(ss.str());
}

