/**
 * @file RoundedSquareGCodeTest.cpp
 * @brief End-to-end test: manufactured G-code → parse → NURBS → ParetoPlanner → WSS validation.
 *
 * @details
 * This test manufactures a G-code program that mimics the structure of real
 * 3D-printer output (rounded square shell with Z-hop "perimeter puncture"
 * patterns, straight grid infill, multiple layers, rapid travel moves,
 * different feed rates for shell vs infill). It then runs the full pipeline:
 *
 *   G-code text → PlanningSegmentBuilder → piecewiseNurbsFromSegments
 *               → PathAdapter (with per-segment feed rates + corner velocities)
 *               → ParetoTimeEnergyOptimalVelocityPlanner
 *               → WSS (Weighted Switching Structure)
 *
 * The WSS is validated for:
 *   - Arc length continuity
 *   - Time continuity
 *   - Velocity continuity (no GAPs)
 *   - Acceleration limit satisfaction
 *   - Jerk limit satisfaction
 *   - Start/end velocity = 0
 *   - Non-negative velocities
 *   - Velocity limit satisfaction at sampled points
 *
 * This is a regression test for the coalescing bug where BANG arcs with
 * different a0 values were merged, producing velocity discontinuities,
 * and for the acceleration-limit violation where the solver applied jerk
 * that pushed acceleration beyond the bounds.
 */

