// ============================================================================
// Test: Full pipeline on manufactured rounded-square G-code
// ============================================================================
//
// This test validates that the ParetoTimeEnergyOptimalVelocityPlanner
// produces a physically valid WSS for a G-code program that mimics real
// 3D-printer output. The G-code includes:
//   - Multiple layers with Z moves
//   - Rounded square shell with Z-hop "perimeter puncture" patterns
//   - Straight grid infill at a different (slower) feed rate
//   - Rapid travel moves between shell and infill
//
// The test checks:
//   1. The G-code parses successfully (non-zero segments)
//   2. The NURBS path is built (non-zero pieces)
//   3. The planner produces a velocity profile (non-null)
//   4. The WSS has no velocity discontinuities (GAPs)
//   5. The WSS has no acceleration limit violations
//   6. The WSS has no jerk limit violations
//   7. Start and end velocities are zero
//   8. All velocities are non-negative
//   9. Arc length continuity (s1[i] == s0[i+1])
//  10. Time continuity (t0[i] + dur[i] == t0[i+1])

TEST(RoundedSquareGCodeTest, FullPipeline_ProducesValidWSS) {
    // Generate G-code for a small rounded square (3 layers, 50mm)
    std::string gcode = generateRoundedSquareGcode(3, 50.0, 2, 5.0);
    ASSERT_FALSE(gcode.empty());

    // Step 1: Parse G-code
    auto parseResult = GCode::PlanningSegmentBuilder::fromText(gcode);
    ASSERT_TRUE(parseResult.error.ok()) << "G-code parsing failed";
    auto& segments = parseResult.segments;
    ASSERT_GT(segments.size(), 10u) << "Too few segments parsed";

    // Step 2: Build NURBS path
    auto nurbsResult = piecewiseNurbsFromSegments(segments);
    ASSERT_GT(nurbsResult.path.numPieces(), 0u) << "No NURBS pieces created";
    ASSERT_GT(nurbsResult.path.totalLength(), 100.0)
        << "Path too short: " << nurbsResult.path.totalLength();

    // Step 3: Build PathAdapter with per-segment feed rates + corner velocities
    PathAdapter<3, double> pathAdapter(nurbsResult.path);
    if (!nurbsResult.feedRates.empty()) {
        pathAdapter.setSegmentVelocityLimits(nurbsResult.feedRates);
        pathAdapter.computeCornerVelocities(0.05, 2000.0);
    }

    // Step 4: Run ParetoPlanner
    KinematicLimits<3, double> limits;
    limits.path.maxPathVelocity = 200.0;
    limits.path.maxPathAcceleration = 2000.0;
    limits.path.maxPathJerk = 20000.0;
    limits.path.jerkLimitEnabled = true;
    limits.path.maxCentripetalAcceleration = 2000.0;
    for (int i = 0; i < 3; ++i) {
        limits.axis.maxVelocity[i] = 200.0;
        limits.axis.maxAcceleration[i] = 2000.0;
        limits.axis.maxJerk[i] = 20000.0;
    }
    limits.axis.jerkLimitEnabled = true;

    double feedRate = 200.0;
    std::size_t numSamples = std::min<std::size_t>(
        20000, std::max<std::size_t>(200, pathAdapter.numSegments() * 20));

    ParetoTimeEnergyOptimalVelocityPlanner<3, double> profiler(limits);
    auto velocityProfile = profiler.computeProfile(
        pathAdapter, feedRate, 0.0, 0.0, numSamples);
    ASSERT_NE(velocityProfile, nullptr) << "Planner returned null profile";

    // Step 5: Extract WSS
    auto wss = profiler.weightedSource();
    ASSERT_NE(wss, nullptr) << "weightedSource() returned null";
    const auto& arcs = wss->arcs();
    ASSERT_GT(arcs.size(), 10u) << "Too few arcs in WSS";

    // ── Validation ──────────────────────────────────────────────────────

    // 1. Arc length continuity: s1[i] == s0[i+1]
    for (size_t i = 1; i < arcs.size(); ++i) {
        double gap = std::abs(arcs[i].s0 - arcs[i-1].s1);
        EXPECT_LT(gap, 1e-6) << "Arc length discontinuity at arc " << i;
    }

    // 2. Time continuity: t0[i] + dur[i] == t0[i+1]
    for (size_t i = 1; i < arcs.size(); ++i) {
        double prevEnd = arcs[i-1].t0 + arcs[i-1].duration;
        double gap = std::abs(arcs[i].t0 - prevEnd);
        EXPECT_LT(gap, 1e-6) << "Time discontinuity at arc " << i;
    }

    // 3. Velocity continuity: vEnd[i] == v0[i+1] (no GAPs)
    //    Tolerance: 1e-3 mm/s (accounts for floating-point accumulation)
    double maxVelGap = 0.0;
    for (size_t i = 1; i < arcs.size(); ++i) {
        double prevVEnd = arcEndVelocity(arcs[i-1]);
        double gap = std::abs(arcs[i].v0 - prevVEnd);
        if (gap > maxVelGap) maxVelGap = gap;
        EXPECT_LT(gap, 1e-3)
            << "Velocity GAP at arc " << i
            << ": prevVEnd=" << prevVEnd
            << " currV0=" << arcs[i].v0
            << " gap=" << gap;
    }

    // 4. Acceleration limit: |a0| and |aEnd| <= maxAccel for all arcs
    double maxAccel = 2000.0;
    double maxAccelSeen = 0.0;
    for (size_t i = 0; i < arcs.size(); ++i) {
        double aEnd = arcEndAcceleration(arcs[i]);
        EXPECT_LE(std::abs(arcs[i].a0), maxAccel + 1e-3)
            << "Acceleration limit violated at arc " << i
            << " a0=" << arcs[i].a0;
        EXPECT_LE(std::abs(aEnd), maxAccel + 1e-3)
            << "Acceleration limit violated at arc " << i
            << " aEnd=" << aEnd;
        maxAccelSeen = std::max(maxAccelSeen, std::max(
            std::abs(arcs[i].a0), std::abs(aEnd)));
    }

    // 5. Jerk limit: |eta| <= maxJerk for all arcs
    double maxJerk = 20000.0;
    for (size_t i = 0; i < arcs.size(); ++i) {
        EXPECT_LE(std::abs(arcs[i].eta), maxJerk + 1e-3)
            << "Jerk limit violated at arc " << i
            << " eta=" << arcs[i].eta;
    }

    // 6. Start velocity = 0
    EXPECT_LT(std::abs(arcs.front().v0), 1e-3)
        << "Start velocity not zero: " << arcs.front().v0;

    // 7. End velocity = 0
    double endV = arcEndVelocity(arcs.back());
    EXPECT_LT(std::abs(endV), 1e-3)
        << "End velocity not zero: " << endV;

    // 8. Non-negative velocities
    for (size_t i = 0; i < arcs.size(); ++i) {
        EXPECT_GE(arcs[i].v0, -1e-6)
            << "Negative velocity at arc " << i << ": " << arcs[i].v0;
        double vEnd = arcEndVelocity(arcs[i]);
        EXPECT_GE(vEnd, -1e-6)
            << "Negative end velocity at arc " << i << ": " << vEnd;
    }

    // 9. Total arc length matches path
    double totalArcLen = arcs.back().s1 - arcs.front().s0;
    double pathLen = pathAdapter.totalLength();
    EXPECT_NEAR(totalArcLen, pathLen, 1.0)
        << "Total arc length doesn't match path length";

    // Print summary for debugging
    std::cout << "RoundedSquareGCodeTest summary:\n"
              << "  Segments: " << segments.size() << "\n"
              << "  NURBS pieces: " << nurbsResult.path.numPieces() << "\n"
              << "  Path length: " << pathLen << " mm\n"
              << "  WSS arcs: " << arcs.size() << "\n"
              << "  Total time: " << wss->totalTime() << " s\n"
              << "  Max velocity gap: " << maxVelGap << " mm/s\n"
              << "  Max acceleration seen: " << maxAccelSeen << " mm/s²\n";
}

