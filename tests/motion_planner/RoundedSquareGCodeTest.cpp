/// Generate a rounded-square G-code program with shell + grid infill.
///
/// @param numLayers    Number of print layers
/// @param size         Square side length (mm)
/// @param shellLoops   Number of perimeter/shell loops
/// @param infillSpacing Distance between infill lines (mm)
/// @return G-code text
std::string generateRoundedSquareGcode(int numLayers, double size,
                                       int shellLoops, double infillSpacing) {
    std::ostringstream os;

    // Feed rates (mm/min, as in real G-code)
    const int F_TRAVEL = 18000;
    const int F_PERIMETER = 14400;
    const int F_INFILL = 2400;
    const int F_ZMOVE = 1200;
    const int F_PUNCTURE = 240;

    const double layerHeight = 0.3;
    const double cornerRadius = std::min(10.0, size * 0.1);
    const double shellInset = 2.0;

    // Header
    os << "; Generated by RoundedSquareGCodeTest\n";
    os << "G21 ; set units to mm\n";
    os << "G90 ; absolute XYZ positioning\n";
    os << "G92 E0 ; reset extrusion distance\n";
    os << "G28 ; home all axes\n";

    for (int layer = 0; layer < numLayers; ++layer) {
        double z = layerHeight * (layer + 1);
        os << "; Layer " << layer << "\n";
        os << "G0 Z" << z << " F" << F_ZMOVE << "\n";

        // --- Shell loops ---
        for (int loop = 0; loop < shellLoops; ++loop) {
            double r = std::max(1.0, cornerRadius - loop * shellInset * 0.5);
            double s = std::max(10.0, size - loop * shellInset * 2);

            // Generate rounded square points (CCW)
            // Corner centers
            struct Pt { double x, y; };
            double half = s / 2.0;
            Pt centers[] = {
                {half - r, half - r},  // bottom-left
                {half + s - r - half, half - r},  // bottom-right → (s/2 + s/2 - r, s/2 - r) = (s-r, s/2-r)
            };
            // Simpler: just use 4 corners with arcs
            // Bottom-left center: (r, r), start angle 180
            // Bottom-right center: (s-r, r), start angle 270
            // Top-right center: (s-r, s-r), start angle 0
            // Top-left center: (r, s-r), start angle 90
            Pt cornerCenters[] = {
                {r, r},
                {s - r, r},
                {s - r, s - r},
                {r, s - r},
            };
            double startAngles[] = {180.0, 270.0, 0.0, 90.0};

            std::vector<Pt> pts;
            const int segPerCorner = 8;
            for (int c = 0; c < 4; ++c) {
                double a0 = startAngles[c] * M_PI / 180.0;
                double a1 = a0 + M_PI / 2.0;
                for (int j = 0; j < segPerCorner; ++j) {
                    double t = static_cast<double>(j) / segPerCorner;
                    double a = a0 + t * (a1 - a0);
                    pts.push_back({cornerCenters[c].x + r * std::cos(a),
                                   cornerCenters[c].y + r * std::sin(a)});
                }
            }
            pts.push_back(pts[0]);  // close loop

            // Travel to start
            os << "G0 X" << pts[0].x << " Y" << pts[0].y
               << " F" << F_TRAVEL << "\n";

            // Z-hop perimeter puncture
            os << "G1 Z" << (z - 0.4) << " F" << F_PUNCTURE << " ; perimeter puncture\n";
            os << "G1 Z" << z << " F" << F_PUNCTURE << "\n";

            // Extrude around shell
            for (size_t i = 1; i < pts.size(); ++i) {
                double dx = pts[i].x - pts[i-1].x;
                double dy = pts[i].y - pts[i-1].y;
                double e = 0.05 * std::hypot(dx, dy);
                os << "G1 X" << pts[i].x << " Y" << pts[i].y
                   << " E" << e << " F" << F_PERIMETER << "\n";

                // Insert perimeter puncture every 8 segments
                if (i % 8 == 0 && i < pts.size() - 1) {
                    os << "G1 Z" << (z - 0.4) << " F" << F_PUNCTURE
                       << " ; perimeter puncture\n";
                    os << "G1 Z" << z << " F" << F_PUNCTURE << "\n";
                }
            }
        }

        // --- Grid infill (X direction) ---
        double xStart = cornerRadius;
        double xEnd = size - cornerRadius;
        double yStart = cornerRadius;
        double yEnd = size - cornerRadius;

        int lineIdx = 0;
        for (double y = yStart; y <= yEnd + 0.01; y += infillSpacing) {
            if (lineIdx % 2 == 0) {
                os << "G0 X" << xStart << " Y" << y << " F" << F_TRAVEL << "\n";
                double e = 0.05 * (xEnd - xStart);
                os << "G1 X" << xEnd << " Y" << y << " E" << e
                   << " F" << F_INFILL << "\n";
            } else {
                os << "G0 X" << xEnd << " Y" << y << " F" << F_TRAVEL << "\n";
                double e = 0.05 * (xEnd - xStart);
                os << "G1 X" << xStart << " Y" << y << " E" << e
                   << " F" << F_INFILL << "\n";
            }
            ++lineIdx;
        }

        // --- Grid infill (Y direction) ---
        lineIdx = 0;
        for (double x = xStart; x <= xEnd + 0.01; x += infillSpacing) {
            if (lineIdx % 2 == 0) {
                os << "G0 X" << x << " Y" << yStart << " F" << F_TRAVEL << "\n";
                double e = 0.05 * (yEnd - yStart);
                os << "G1 X" << x << " Y" << yEnd << " E" << e
                   << " F" << F_INFILL << "\n";
            } else {
                os << "G0 X" << x << " Y" << yEnd << " F" << F_TRAVEL << "\n";
                double e = 0.05 * (yEnd - yStart);
                os << "G1 X" << x << " Y" << yStart << " E" << e
                   << " F" << F_INFILL << "\n";
            }
            ++lineIdx;
        }
    }

    os << "; End of G-code\n";
    os << "M84 ; disable motors\n";
    return os.str();
}

/// Compute the end velocity of an arc from its parameters.
double arcEndVelocity(const WeightedArc& a) {
    if (a.type == WeightedArcType::DWELL) return 0.0;
    if (a.type == WeightedArcType::SINGULAR) {
        return a.v0 + a.a_star * a.duration;
    } else if (a.type == WeightedArcType::WALL) {
        return a.v0;
    } else {
        return a.v0 + a.a0 * a.duration
             + 0.5 * a.eta * a.duration * a.duration;
    }
}

/// Compute the end acceleration of an arc.
double arcEndAcceleration(const WeightedArc& a) {
    if (a.type == WeightedArcType::DWELL) return 0.0;
    if (a.type == WeightedArcType::SINGULAR) {
        return a.a_star;
    } else if (a.type == WeightedArcType::WALL) {
        return 0.0;
    } else {
        return a.a0 + a.eta * a.duration;
    }
}

